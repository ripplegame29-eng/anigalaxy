"use client";

import { usePathname } from "next/navigation";

/**
 * Показывает содержимое только на страницах публичного сайта.
 *
 * Панель управления живёт в том же корневом layout, что и сайт, поэтому
 * шапка, подвал, чат и фоновые эффекты попадали и на /admin: админка
 * открывалась внутри тёмной витрины, хотя у неё своя тема и свой каркас.
 *
 * `usePathname` доступен и при серверном рендере клиентского компонента,
 * поэтому на /admin разметка не появится сразу — без мигания шапки до
 * гидратации.
 *
 * Обёртка именно вокруг готовых узлов, а не перенос сайта в route group:
 * так не нужно перекладывать три десятка папок `app/` и рисковать
 * маршрутами ради одного условия.
 */
export function SiteOnly({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();

  if (pathname === "/admin" || pathname?.startsWith("/admin/")) {
    return null;
  }

  return <>{children}</>;
}
