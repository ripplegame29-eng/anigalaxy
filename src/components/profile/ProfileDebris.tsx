"use client";

/**
 * Обломки темы повреждения — декоративный слой поверх профиля.
 *
 * На animeon.cc это строки вида `⌗▒1⌗F░` и `ERR_SIGNAL_LOST`, разбросанные
 * по карточке и мигающие короткими кадрами. Здесь то же самое: глифы
 * мерцают `steps(1)`, а не плавно, иначе это уже не «сломанный сигнал»,
 * а обычное появление текста.
 *
 * Настоящие числа профиля не трогаются: мусор живёт отдельным слоем поверх.
 * В витрине не должно быть ничего, что можно прочесть как данные.
 *
 * Позиции заданы в процентах и не «прыгают» при ресайзе — слой тянется за
 * карточкой, а не за экраном.
 */

const GLYPHS = [
  { текст: "⌗▒1⌗F░", левый: "4%", верх: "24%" },
  { текст: "▚F▞7", левый: "72%", верх: "18%" },
  { текст: "░◦▒░", левый: "88%", верх: "62%" },
  { текст: "E▓B", левый: "8%", верх: "71%" },
];

const ERRORS = [
  { текст: "ERR_SIGNAL_LOST", левый: "36%", верх: "15%" },
  { текст: "ERR_FRAME_DESYNC", левый: "80%", верх: "44%" },
  { текст: "ERR_CHANNEL_LOST", левый: "16%", верх: "48%" },
];

export function ProfileDebris() {
  return (
    <div className="ag-fx-debris" aria-hidden>
      {GLYPHS.map((item) => (
        <i key={item.текст} className="is-glyph" style={{ left: item.левый, top: item.верх }}>
          {item.текст}
        </i>
      ))}
      {ERRORS.map((item) => (
        <i key={item.текст} className="is-err" style={{ left: item.левый, top: item.верх }}>
          {item.текст}
        </i>
      ))}
    </div>
  );
}