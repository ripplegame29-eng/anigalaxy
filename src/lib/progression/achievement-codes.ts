/**
 * Коды достижений — «Семья {N} — Титул {N}».
 *
 * Формат взят из макетов 1:1:
 *   «Ночной дозор II — Страж II»
 *   «Охотник VI — Магистр VI»
 *   «Пожиратель серий VII — Архонт VII»
 *
 * Слева — семейство (что именно ты делал: смотрел серии, голосовал,
 * копил серию дней подряд), справа — титул, который эта ступень даёт.
 * Римская цифра одна и та же с обеих сторон: это и есть сам код.
 * Благодаря общей цифре код читается как координата —
 * «VI» сразу говорит и номер ступени, и её вес.
 *
 * Титулы заданы отдельно для каждого семейства, как в макетах: III в
 * «Сэнпай» — это «Наставник», а III в «Голос зала» — «Адепт».
 */

/** Римские цифры до X — ступени длиннее в конфиге не встречаются */
export const ROMAN = [
  "", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X",
] as const;

export function roman(n: number): string {
  return ROMAN[n] ?? String(n);
}

