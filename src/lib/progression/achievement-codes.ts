export interface AchievementCode {
  /** «Ночной дозор» */
  family: string;
  /** 2 */
  tier: number;
  /** «II» */
  roman: string;
  /** «Страж» */
  title: string;
  /** «Ночной дозор II — Страж II» */
  text: string;
  /**
   * Разобранный текст для рендера: римские цифры помечены флагом,
   * чтобы интерфейс подсветить их цветом семейства (как `.aw-rom` в макете).
   */
  parts: Array<{ text: string; roman: boolean }>;
}

/** Короткий код для компактных мест (тосты, логи): «Ночной дозор II» */
export function achievementCodeShort(family: string, tier: number): string {
  return `${FAMILY_SUBTITLE[family] ?? family} ${roman(tier)}`;
}

/**
 * Разбор готовой строки кода на части для подсветки римских цифр.
 *
 * Регулярное выражение — то же, что в макетах: римская цифра определяется
 * как отдельное слово из I/V/X. Нужен для кодов, заданных дословно
 * (у переодетых достижений они приходят из медали, а не собираются из
 * семейства).
 */
export function parseCode(text: string): Array<{ text: string; roman: boolean }> {
  return text
    .split(/(\b[IVX]{1,4}\b)/)
    .filter((part) => part !== "")
    .map((part) => ({ text: part, roman: /^[IVX]{1,4}$/.test(part) }));
}

export function achievementCode(family: string, tier: number): AchievementCode {
  const r = roman(tier);
  const title = FAMILY_TITLES[family]?.[tier - 1] ?? "";
  const left = FAMILY_SUBTITLE[family] ?? family;
  return {
    family: left,
    tier,
    roman: r,
    title,
    text: title ? `${left} ${r} — ${title} ${r}` : `${left} ${r}`,
    parts: title
      ? [
          { text: `${left} `, roman: false },
          { text: r, roman: true },
          { text: ` — ${title} `, roman: false },
          { text: r, roman: true },
        ]
      : [
          { text: `${left} `, roman: false },
          { text: r, roman: true },
        ],
  };
}