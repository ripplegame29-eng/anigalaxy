/* ------------------------------- Хелперы --------------------------------- */

/** Название тайтла — в подборке это строка либо объект с постером */
export function itemTitle(item: string | { t: string; poster?: string }): string {
  return typeof item === "string" ? item : item.t;
}

/** «4,2K» — как в макете */
export function formatCount(n: number): string {
  if (n < 1000) return String(n);
  return `${(n / 1000).toFixed(n % 1000 ? 1 : 0).replace(".", ",")}K`;
}

/** Русские окончания: `plural(3, ["подборка", "подборки", "подборок"])` */
export function plural(n: number, forms: [string, string, string]): string {
  const a = n % 10;
  const b = n % 100;
  if (a === 1 && b !== 11) return forms[0];
  if (a >= 2 && a <= 4 && (b < 10 || b >= 20)) return forms[1];
  return forms[2];
}

/** «сегодня / вчера / 3 дн. назад / 2 нед. назад / 5 мес. назад» */
export function ago(days: number): string {
  if (days === 0) return "сегодня";
  if (days < 2) return "вчера";
  if (days < 7) return `${days} дн. назад`;
  if (days < 30) return `${Math.floor(days / 7)} нед. назад`;
  return `${Math.floor(days / 30)} мес. назад`;
}

/** Оттенок обложки по названию — тем же способом, что в макете */
export function hueOf(text: string): number {
  let h = 0;
  for (const c of text) h = (h * 31 + c.charCodeAt(0)) % 360;
  return h;
}

/**
 * Название тайтла в сравнимом виде: без регистра, пунктуации и лишних
 * пробелов. Так обложка ищется в индексе постеров (см. `collections-posters`),
 * а сам вид может оставаться клиентским компонентом.
 */
export function normalizeTitle(value: string): string {
  return value
    .toLowerCase()
    .replace(/[«»"'`.!?,()[\]:;—–-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** Доля отмеченных тайтлов подборки, 0…1 */
export function collectionProgress(collection: Collection, watched: number[]): number {
  if (collection.items.length === 0) return 0;
  return Math.min(1, watched.length / collection.items.length);
}

export type SortKey = "views" | "likes" | "size" | "date" | "prog";

export type CollectionsFilter = {
  tab: "pop" | "new" | "ed" | "lk" | "my";
  tags: Set<string>;
  query: string;
  sort: SortKey;
  author: string | null;
  /** Лайкнутые подборки */
  liked: Set<number>;
  /** Свои подборки */
  mine: Set<number>;
  /** Отметки просмотра: id подборки → индексы тайтлов */
  watched: Record<number, number[]>;
};

/**
 * Отбор подборок под состояние витрины.
 *
 * Порядок фильтров и правила вкладок — как в макете: «Новое» ограничено
 * двумя неделями, «Мои» показывает и свои подборки, и те, где отмечен хоть
 * один тайтл.
 */
export function filterCollections(
  all: Collection[],
  state: CollectionsFilter,
): Collection[] {
  const query = state.query.trim().toLowerCase();

  const list = all.filter((c) => {
    if (state.tab === "new" && c.age > 14) return false;
    if (state.tab === "ed" && !c.ed) return false;
    if (state.tab === "lk" && !state.liked.has(c.id)) return false;
    if (state.tab === "my" && !state.mine.has(c.id) && !state.watched[c.id]?.length) return false;
    if (state.tags.size && ![...state.tags].every((t) => c.tags.includes(t))) return false;
    if (state.author && c.author !== state.author) return false;
    if (query) {
      const hay = [c.title, c.desc, c.tags.join(" "), c.author, c.items.map(itemTitle).join(" ")]
        .join(" ")
        .toLowerCase();
      if (!hay.includes(query)) return false;
    }
    return true;
  });

  const key: Record<SortKey, (c: Collection) => number> = {
    views: (c) => -c.views,
    likes: (c) => -c.likes,
    size: (c) => -c.items.length,
    date: (c) => c.age,
    prog: (c) => -collectionProgress(c, state.watched[c.id] ?? []),
  };
  return list.sort((a, b) => key[state.sort](a) - key[state.sort](b));
}

/** Авторы витрины: сколько подборок и сколько лайков у каждого */
export function topAuthors(all: Collection[], limit = 8): { name: string; count: number; likes: number }[] {
  const map = new Map<string, { name: string; count: number; likes: number }>();
  for (const c of all) {
    const row = map.get(c.author) ?? { name: c.author, count: 0, likes: 0 };
    row.count += 1;
    row.likes += c.likes;
    map.set(c.author, row);
  }
  return [...map.values()].sort((a, b) => b.likes - a.likes).slice(0, limit);
}

/** Все теги витрины по алфавиту */
export function allTags(all: Collection[]): string[] {
  return [...new Set(all.flatMap((c) => c.tags))].sort();
}

/** Четыре цифры для плитки: тайтл зацикливается, если в подборке их меньше */
export function mosaicItems(collection: Collection): number[] {
  return [0, 1, 2, 3].map((i) => i % collection.items.length);
}

/** Подборки для карусели «выбор редакции» */
export function featured(all: Collection[], limit = 4): Collection[] {
  return [...all].filter((c) => c.ed).sort((a, b) => b.likes - a.likes).slice(0, limit);
}