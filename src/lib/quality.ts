/**
 * Обработка картинки на видео.
 *
 * Раньше здесь был стор с тремя режимами («Оригинал / HD+ / Апскейл 2x») и
 * кнопка под плеером Kodik. Кнопку убрали: настоящий апскейл кадров чужого
 * домена возможен только через Screen Capture API, и браузер при каждом
 * включении спрашивал разрешение показывать вкладку. Вопрос поверх ролика
 * стоил дороже, чем давала картинка. Вместе с кнопкой ушёл и стор: менять
 * было нечем, а сохранённое в localStorage значение продолжало бы управлять
 * фильтром, которого уже никто не включает.
 *
 * Осталось два независимых места, где картинку обрабатывают:
 * — iframe Kodik: только CSS-цепочка, её композитор применяет к уже
 *   отрисованному кадру. SVG-фильтры url(#…) к кадру чужого домена браузер
 *   не применяет вовсе (проверено замерами: 0/255), так что вариантов тут
 *   немного. Сейчас — ничего, ролик показывается как отдаёт источник.
 *   Свой апскейл с настоящими целями 2K/4K остался у альтернативного
 *   плеера AniLiberty (Anime4K поверх локального <video>, см. AltPlayer).
 * — hero-ролики главной: WebGL-шейдер обрабатывает текстуру ролика пиксель в
 *   пиксель (lib/video-shader.ts). Разрешения браузера не нужно — видео наше,
 *   а не кадр чужого iframe, поэтому этот апскейл остался. Значения прежние:
 *   страница выглядит ровно так же, как до снятия кнопки.
 */

